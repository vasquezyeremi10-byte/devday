/** Filas 5 × 7 de un carácter de la fuente del HUD ('1' = píxel), o null. */
export function glyphRows(char: string): string[] | null {
  return GLYPHS[char]?.split('/') ?? null;
}

function registerFont(
  scene: Phaser.Scene,
  key: string,
  image: string,
  glyphs: Record<string, string>,
  width: number,
  height: number,
): void {
  if (scene.cache.bitmapFont.exists(key)) return;
  const chars = Object.keys(glyphs).join('');
  const texture = scene.textures.createCanvas(
    image,
    chars.length * width,
    height,
  )!;
  const ctx = texture.context;
  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = '#ffffff';
  [...chars].forEach((char, index) =>
    glyphs[char]!.split('/').forEach((row, y) => {
      [...row].forEach((pixel, x) => {
        if (pixel === '1') ctx.fillRect(index * width + x, y, 1, 1);
      });
    }),
  );
  texture.refresh();
  texture.setFilter(Phaser.Textures.FilterMode.NEAREST);
  scene.cache.bitmapFont.add(
    key,
    Phaser.GameObjects.RetroFont.Parse(scene, {
      image,
      width,
      height,
      chars,
      charsPerRow: chars.length,
      'offset.x': 0,
      'offset.y': 0,
      'spacing.x': 0,
      'spacing.y': 0,
      lineSpacing: 0,
    }),
  );
}

export function createPixelFont(scene: Phaser.Scene): void {
  registerFont(scene, 'pixel', 'pixel-font', GLYPHS, 6, 8);
  registerFont(scene, 'pixel-xp', 'pixel-font-xp', XP_GLYPHS, 4, 6);
}

/** El tamaño nativo de RetroFont es el ancho de celda: 6, no su altura. */
export function pixelText(
  scene: Phaser.Scene,
  x: number,
  y: number,
  value: string,
  color: number,
): Phaser.GameObjects.BitmapText {
  return scene.add.bitmapText(x, y, 'pixel', value, 6).setTint(color);
}

/** Rótulo pequeño 3 × 5 (celda 4 × 6) para etiquetas del HUD. */
export function smallText(
  scene: Phaser.Scene,
  x: number,
  y: number,
  value: string,
  color: number,
): Phaser.GameObjects.BitmapText {
  return scene.add.bitmapText(x, y, 'pixel-xp', value, 4).setTint(color);
}

export function xpPixelText(
  scene: Phaser.Scene,
  color: number,
): Phaser.GameObjects.BitmapText {
  return scene.add.bitmapText(0, 0, 'pixel-xp', '', 4).setTint(color);
}
